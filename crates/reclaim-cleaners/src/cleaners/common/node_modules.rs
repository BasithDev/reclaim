//! Cleaner: node_modules folders in projects untouched for 30+ days (npm install restores them).


use super::devscan::find_artifacts;
use crate::cleaners::simple::{files_info, never, SimpleFiles};
use crate::util::{days, home, Candidate};
use crate::{Cleaner, CleanerGroup, Risk};

fn collect() -> Vec<Candidate> {
    find_artifacts("node_modules", |p| p.join("package.json").is_file(), |_| true, days(30), "node_modules")
}

pub fn cleaner() -> Box<dyn Cleaner> {
    Box::new(SimpleFiles {
        info: files_info(
            "node-modules",
            "Old node_modules folders",
            "Removes node_modules in projects you have not touched for 30+ days. Run your package manager's install to restore them.",
            CleanerGroup::Developer,
            Risk::Moderate,
            false,
        ),
        available: || home().is_some(),
        roots: || home().map(|h| vec![h]).unwrap_or_default(),
        collect,
        needs_admin: never,
        force_permanent: false,
        post_clean: None,
    })
}
